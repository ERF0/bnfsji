export function setBrowserSecurityHeaders(headers) {
  headers.set("X-Content-Type-Options", "nosniff");
  headers.set("X-Frame-Options", "DENY");
  headers.set("Referrer-Policy", "strict-origin-when-cross-origin");
  headers.set("Permissions-Policy", "camera=(), geolocation=(), microphone=()");
  headers.set("X-Permitted-Cross-Domain-Policies", "none");
  return headers;
}

export function createContentSecurityPolicy(nonce) {
  if (typeof nonce !== "string" || !/^[A-Za-z0-9+/]+={0,2}$/.test(nonce)) {
    throw new TypeError("A valid per-response CSP nonce is required");
  }
  return [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}'`,
    "style-src 'self'",
    "img-src 'self' data: blob:",
    "font-src 'self' data:",
    "connect-src 'self'",
    "worker-src 'self'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    "object-src 'none'",
  ].join("; ");
}
